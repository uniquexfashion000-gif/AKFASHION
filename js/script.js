let WHATSAPP_NUMBER = (typeof _siteConfig !== 'undefined' && _siteConfig.whatsappNumber) ? _siteConfig.whatsappNumber : '1234567890';

function buildWhatsAppMessage(items, subtotal){
  let msg = `*🕰️ AKFASHION Order Request*\n`;
  msg += `━━━━━━━━━━━━━━━━━━━━\n\n`;
  msg += `*Order Items:*\n`;
  items.forEach((it,i)=>{
    msg += `${i+1}. *${it.name}*\n`;
    msg += `   Brand: ${it.brand}\n`;
    msg += `   Qty: ${it.qty} × PKR ${it.price.toLocaleString()} = *PKR ${(it.price*it.qty).toLocaleString()}*\n\n`;
  });
  msg += `━━━━━━━━━━━━━━━━━━━━\n`;
  msg += `*Subtotal:* PKR ${subtotal.toLocaleString()}\n`;
  msg += `*Shipping:* Rs. 250 (All Over Pakistan)\n`;
  msg += `*Total: PKR ${subtotal.toLocaleString()} + Rs. 250 Shipping* 💰\n\n`;
  msg += `Please share my order details and payment information. Thank you!`;
  return msg;
}

function whatsappOrder(id){
  const p = products.find(x => x.id === id);
  if(!p) return;
  const qty = parseInt(document.getElementById('modalQty').textContent);
  const msg = `*🕰️ AKFASHION Order Request*\n━━━━━━━━━━━━━━━━━━━━\n\n*Order Item:*\n• *${p.name}*\n  Brand: ${p.brand}\n  Category: ${p.category}\n  Qty: ${qty} × PKR ${p.price.toLocaleString()} = *PKR ${(p.price*qty).toLocaleString()}*\n\n━━━━━━━━━━━━━━━━━━━━\n*Subtotal: PKR ${(p.price*qty).toLocaleString()}*\n*Shipping: Rs. 250 (All Over Pakistan)*\n*Total: PKR ${(p.price*qty).toLocaleString()} + Rs. 250 Shipping* 💰\n\nPlease share my order details and payment information. Thank you!`;
  const url = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(msg)}`;
  window.open(url,'_blank');
}

function whatsappCheckout(){
  if(cart.length === 0) return;
  const subtotal = cart.reduce((s,i)=>s+(i.price*i.qty),0);
  const msg = buildWhatsAppMessage(cart,subtotal);
  const url = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(msg)}`;
  window.open(url,'_blank');
}

