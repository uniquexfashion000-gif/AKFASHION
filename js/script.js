function initScrollAnimations(){
  const observer = new IntersectionObserver((entries)=>{
    entries.forEach(entry=>{
      if(entry.isIntersecting){
        entry.target.classList.add('in');
        observer.unobserve(entry.target);
      }
    });
  },{threshold:0.1,rootMargin:'0px 0px -50px 0px'});
  document.querySelectorAll('.reveal').forEach(el=>observer.observe(el));
}

function initReplicaHourMarks(){
  const container = document.getElementById('hourMarksReplica');
  if(!container) return;
  container.style.cssText = 'position:absolute;inset:0;pointer-events:none;';
  let html = '';
  for(let i=0;i<12;i++){
    const rot = i*30;
    const isMajor = i%3===0;
    const cls = isMajor ? 'major' : 'minor';
    html += `<div class="hour-mark ${cls}" style="--rotation:${rot}deg; position:absolute; top:50%; left:50%;"></div>`;
  }
  container.innerHTML = html;

  /* Numerals — positioned with trig so they stay upright and scale responsively */
  const numbers = document.getElementById('hourNumbersReplica');
  if(numbers){
    const radius = 40; /* percent of face radius from center */
    let numHtml = '';
    for(let i=1;i<=12;i++){
      const angleDeg = i*30 - 90;
      const angleRad = angleDeg*Math.PI/180;
      const x = 50 + radius*Math.cos(angleRad);
      const y = 50 + radius*Math.sin(angleRad);
      numHtml += `<div class="hour-number" style="left:${x}%; top:${y}%; transform:translate(-50%,-50%);">${i}</div>`;
    }
    numbers.innerHTML = numHtml;
  }
}

function startWatch(){
  function tick(){
    const now = new Date();
    const h = now.getHours() % 12;
    const m = now.getMinutes();
    const s = now.getSeconds();
    
    const hDeg = (h*30) + (m*0.5);
    const mDeg = m*6 + (s*0.1);
    const sDeg = s*6;
    
    document.getElementById('handHour').style.transform = `translate(-50%,-100%) rotate(${hDeg}deg)`;
    document.getElementById('handMinute').style.transform = `translate(-50%,-100%) rotate(${mDeg}deg)`;
    document.getElementById('handSecond').style.transform = `translate(-50%,-100%) rotate(${sDeg}deg)`;
  }
  tick();
  setInterval(tick,1000);
}

